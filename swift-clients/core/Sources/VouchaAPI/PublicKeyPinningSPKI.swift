import Foundation

#if canImport(Security)
    import Security

    extension PublicKeyPinningURLSessionDelegate {
        static func spkiHeader(keyType: String, keySize: Int) -> Data? {
            if keyType == kSecAttrKeyTypeRSA as String {
                return rsaSPKIHeader(keySize: keySize)
            }
            if keyType == kSecAttrKeyTypeECSECPrimeRandom as String {
                return ecSPKIHeader(keySize: keySize)
            }
            return nil
        }

        private static func rsaSPKIHeader(keySize: Int) -> Data? {
            switch keySize {
            case 2_048:
                Data([
                    0x30, 0x82, 0x01, 0x22, 0x30, 0x0D, 0x06, 0x09,
                    0x2A, 0x86, 0x48, 0x86, 0xF7, 0x0D, 0x01, 0x01,
                    0x01, 0x05, 0x00, 0x03, 0x82, 0x01, 0x0F, 0x00
                ])
            case 3_072:
                Data([
                    0x30, 0x82, 0x01, 0xA2, 0x30, 0x0D, 0x06, 0x09,
                    0x2A, 0x86, 0x48, 0x86, 0xF7, 0x0D, 0x01, 0x01,
                    0x01, 0x05, 0x00, 0x03, 0x82, 0x01, 0x8F, 0x00
                ])
            case 4_096:
                Data([
                    0x30, 0x82, 0x02, 0x22, 0x30, 0x0D, 0x06, 0x09,
                    0x2A, 0x86, 0x48, 0x86, 0xF7, 0x0D, 0x01, 0x01,
                    0x01, 0x05, 0x00, 0x03, 0x82, 0x02, 0x0F, 0x00
                ])
            default:
                nil
            }
        }

        private static func ecSPKIHeader(keySize: Int) -> Data? {
            switch keySize {
            case 256:
                Data([
                    0x30, 0x59, 0x30, 0x13, 0x06, 0x07, 0x2A, 0x86,
                    0x48, 0xCE, 0x3D, 0x02, 0x01, 0x06, 0x08, 0x2A,
                    0x86, 0x48, 0xCE, 0x3D, 0x03, 0x01, 0x07, 0x03,
                    0x42, 0x00
                ])
            case 384:
                Data([
                    0x30, 0x76, 0x30, 0x10, 0x06, 0x07, 0x2A, 0x86,
                    0x48, 0xCE, 0x3D, 0x02, 0x01, 0x06, 0x05, 0x2B,
                    0x81, 0x04, 0x00, 0x22, 0x03, 0x62, 0x00
                ])
            default:
                nil
            }
        }
    }
#endif
